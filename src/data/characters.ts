// Данные о персонажах и NPC

export interface Character {
  id: string;
  name: string;
  role: string;
  location: string;
  description: string;
  questline?: string;
  appearsOnShip?: boolean;
  affectsEnding?: boolean;
  traits?: string[];
}

export interface Companion {
  id: string;
  name: string;
  type: 'unique' | 'mercenary' | 'special';
  hireCost: string;
  abilities: string;
  notes: string;
  canDie?: boolean;
}

export interface Enemy {
  id: string;
  name: string;
  location: string;
  hp: string;
  def: string;
  weakness: string;
  notes: string;
}

